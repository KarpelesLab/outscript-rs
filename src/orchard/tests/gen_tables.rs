//! Regenerates the tables of precomputed curve points (`constants/*.rs`).
//!
//! Run with
//! `OUTSCRIPT_GEN_TABLES=src/orchard/constants cargo test gen_tables -- --ignored`
//! then `cargo fmt`. The regular tests check every table entry against the
//! hash-to-curve it comes from, so this is only needed to rebuild the files.

use crate::orchard::pallas::{Affine, Point};
use std::fmt::Write;

fn limbs(l: [u64; 4]) -> String {
    format!(
        "[0x{:016x}, 0x{:016x}, 0x{:016x}, 0x{:016x}]",
        l[0], l[1], l[2], l[3]
    )
}

fn point(p: &Affine) -> String {
    format!(
        "({}, {})",
        limbs(p.x().to_montgomery()),
        limbs(p.y().to_montgomery())
    )
}

#[test]
#[ignore = "writes source files"]
fn gen_tables() {
    let Ok(dir) = std::env::var("OUTSCRIPT_GEN_TABLES") else {
        return;
    };
    let mut points = vec![Point::IDENTITY; 1024];
    for (j, p) in points.iter_mut().enumerate() {
        *p = Point::hash_to_curve(b"z.cash:SinsemillaS", &(j as u32).to_le_bytes());
    }
    let mut affine = vec![Affine::IDENTITY; 1024];
    Point::batch_normalize(&points, &mut affine);
    let mut out = String::from(
        "//! The Sinsemilla generators `S(j)` for every 10-bit `j`, as affine (x, y) in\n\
         //! Montgomery form. Generated by `tests/gen_tables.rs`; a test checks every\n\
         //! entry against the hash-to-curve that defines it.\n\n\
         #[rustfmt::skip]\n\
         pub(super) static S_RAW: [([u64; 4], [u64; 4]); 1024] = [\n",
    );
    for p in &affine {
        writeln!(out, "    {},", point(p)).unwrap();
    }
    out.push_str("];\n");
    std::fs::write(format!("{dir}/sinsemilla_s.rs"), out).unwrap();

    let bases: [(&str, &[u8], &[u8]); 9] = [
        ("SPEND_AUTH_G", b"z.cash:Orchard", b"G"),
        ("NULLIFIER_K", b"z.cash:Orchard", b"K"),
        ("VALUE_COMMIT_V", b"z.cash:Orchard-cv", b"v"),
        ("VALUE_COMMIT_R", b"z.cash:Orchard-cv", b"r"),
        ("NOTE_COMMIT_R", b"z.cash:Orchard-NoteCommit-r", b""),
        (
            "NOTE_COMMIT_Q",
            b"z.cash:SinsemillaQ",
            b"z.cash:Orchard-NoteCommit-M",
        ),
        ("COMMIT_IVK_R", b"z.cash:Orchard-CommitIvk-r", b""),
        (
            "COMMIT_IVK_Q",
            b"z.cash:SinsemillaQ",
            b"z.cash:Orchard-CommitIvk-M",
        ),
        (
            "MERKLE_CRH_Q",
            b"z.cash:SinsemillaQ",
            b"z.cash:Orchard-MerkleCRH",
        ),
    ];
    let mut out = String::from(
        "//! The fixed generators of Orchard, as affine (x, y) in Montgomery form.\n\
         //! Generated by `tests/gen_tables.rs`; a test checks each against the\n\
         //! hash-to-curve that defines it and against the official vectors.\n\n",
    );
    for (name, domain, msg) in bases {
        let p = Point::hash_to_curve(domain, msg).to_affine();
        writeln!(
            out,
            "#[rustfmt::skip]\npub(super) const {name}_RAW: ([u64; 4], [u64; 4]) = {};",
            point(&p)
        )
        .unwrap();
    }
    std::fs::write(format!("{dir}/fixed_bases.rs"), out).unwrap();
}
