/// The version of the Orchard Action circuit that proofs must be made for
/// under a consensus branch, or `None` for a branch this crate does not
/// know, for which the caller chooses with
/// [`Builder::set_orchard_circuit_version`]:
/// [`CircuitVersion::for_branch_id`], which has the sources of the
/// mapping (NU5, NU6 and NU6.1: the original circuit; NU6.2: the corrected
/// one; NU6.3 and NU7: the one with the cross-address restriction, which
/// the Ironwood pool shares).
#[cfg(feature = "zcash-orchard-prover")]
pub const fn orchard_circuit_version(consensus_branch_id: u32) -> Option<CircuitVersion> {
    CircuitVersion::for_branch_id(consensus_branch_id)
}

/// What creates the proofs of the shielded parts: nothing for a
/// transparent transaction, the Sapling parameters for Sapling spends and
/// outputs, the Orchard proving key for anything Orchard.
#[derive(Clone, Copy, Default)]
pub struct Provers<'a> {
    #[cfg(feature = "zcash-sapling-prover")]
    sapling_spend: Option<&'a crate::sapling::prover::SpendParameters>,
    #[cfg(feature = "zcash-sapling-prover")]
    sapling_output: Option<&'a crate::sapling::prover::OutputParameters>,
    #[cfg(feature = "zcash-orchard-prover")]
    orchard: Option<&'a crate::orchard::circuit::ProvingKey>,
    _marker: PhantomData<&'a ()>,
}

impl core::fmt::Debug for Provers<'_> {
    fn fmt(&self, f: &mut core::fmt::Formatter<'_>) -> core::fmt::Result {
        f.debug_struct("Provers").finish_non_exhaustive()
    }
}

impl<'a> Provers<'a> {
    /// No prover: enough for a transaction without shielded parts.
    pub fn new() -> Self {
        Self::default()
    }

    /// With the Sapling Spend parameters (the contents of
    /// `sapling-spend.params`), needed when there are Sapling spends.
    #[cfg(feature = "zcash-sapling-prover")]
    pub fn sapling_spend(mut self, params: &'a crate::sapling::prover::SpendParameters) -> Self {
        self.sapling_spend = Some(params);
        self
    }

    /// With the Sapling Output parameters (the contents of
    /// `sapling-output.params`), needed when there are Sapling outputs.
    #[cfg(feature = "zcash-sapling-prover")]
    pub fn sapling_output(mut self, params: &'a crate::sapling::prover::OutputParameters) -> Self {
        self.sapling_output = Some(params);
        self
    }

    /// With the Orchard proving key, which must be of the circuit version
    /// of the transaction ([`Builder::orchard_circuit_version`]); needed
    /// when there are Orchard or Ironwood spends or outputs (the Ironwood
    /// pool uses the circuit of NU6.3,
    /// [`CircuitVersion::PostNu6_3`], which is that of the Orchard pool
    /// under every branch that has an Ironwood pool).
    #[cfg(feature = "zcash-orchard-prover")]
    pub fn orchard(mut self, pk: &'a crate::orchard::circuit::ProvingKey) -> Self {
        self.orchard = Some(pk);
        self
    }
}

/// A transparent input and what signs it.
struct TransparentInput<'k> {
    /// What makes the scriptSig, or `None` for signatures made elsewhere.
    signer: Option<InputSigner<'k>>,
    /// The sighash type of the signatures.
    hash_type: u8,
    txid: [u8; 32],
    vout: u32,
    sequence: u32,
    amount: u64,
    script: Vec<u8>,
    /// The most bytes the scriptSig can take, which the fee counts.
    script_sig_len: usize,
}

impl TransparentInput<'_> {
    /// The serialized size of the input, once signed, at most.
    fn size(&self) -> usize {
        36 + crate::BtcVarInt(self.script_sig_len as u64).len() + self.script_sig_len + 4
    }
}

/// How the fee of a transaction is decided when the builder funds it
/// ([`Builder::fund`]).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum FeeRule {
    /// The conventional fee of ZIP 317 for the transaction as it will be,
    /// change included.
    Zip317,
    /// This fee, in zatoshis, whatever the transaction is.
    Fixed(u64),
}

/// Where the value a transaction neither sends nor pays as its fee goes:
/// the change, for [`Builder::fund`].
#[derive(Clone, Copy)]
pub enum Change<'a> {
    /// To a transparent output with this scriptPubKey.
    Transparent(&'a [u8]),
    /// To a Sapling output at `to`, an address of the sender: ordinarily
    /// the default address of the *internal* full viewing key of the
    /// account (ZIP 32:
    /// `sapling::zip32::ExtendedFullViewingKey::internal`), which is never
    /// given to anyone, with the internal outgoing viewing key. `random`
    /// is as for [`Builder::add_sapling_output`]. A Sapling anchor, if the
    /// transaction has Sapling spends, must be set before.
    #[cfg(feature = "zcash-sapling-prover")]
    Sapling {
        /// The outgoing viewing key that will recover the change.
        ovk: Option<&'a crate::sapling::keys::OutgoingViewingKey>,
        /// The address of the sender the change goes to.
        to: &'a crate::sapling::keys::PaymentAddress,
        /// Fresh random bytes.
        random: &'a [u8; crate::sapling::builder::OUTPUT_RANDOM_SIZE],
    },
    /// To the Orchard pool, at the internal address of this spending key
    /// (ZIP 32: `fvk.address_at(0, Scope::Internal)`), recoverable with
    /// its internal outgoing viewing key: see
    /// [`Builder::add_orchard_change`]. From NU6.3 only value that the
    /// transaction spends from the Orchard pool can stay in it.
    #[cfg(feature = "zcash-orchard-prover")]
    Orchard(&'a crate::orchard::keys::SpendingKey),
    /// To the Ironwood pool (a version 6 transaction), at the internal
    /// address of this full viewing key, recoverable with its internal
    /// outgoing viewing key: see [`Builder::add_ironwood_change`].
    #[cfg(feature = "zcash-orchard-prover")]
    Ironwood(&'a crate::orchard::keys::FullViewingKey),
}

impl core::fmt::Debug for Change<'_> {
    fn fmt(&self, f: &mut core::fmt::Formatter<'_>) -> core::fmt::Result {
        f.write_str(match self {
            Change::Transparent(_) => "Transparent",
            #[cfg(feature = "zcash-sapling-prover")]
            Change::Sapling { .. } => "Sapling",
            #[cfg(feature = "zcash-orchard-prover")]
            Change::Orchard(_) => "Orchard",
            #[cfg(feature = "zcash-orchard-prover")]
            Change::Ironwood(_) => "Ironwood",
        })
    }
}

