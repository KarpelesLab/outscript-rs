/// Why a transaction could not be built.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
#[non_exhaustive]
pub enum Error {
    /// A transparent part is invalid, or the transaction could not be
    /// digested, signed or serialized: see the inner error. A transparent
    /// input that does not spend a P2PKH output is
    /// [`UnsupportedScript`](crate::Error::UnsupportedScript), one whose
    /// key is not that of the output
    /// [`KeyNotInvolved`](crate::Error::KeyNotInvolved).
    Tx(crate::Error),
    /// The Sapling bundle could not be built or signed.
    #[cfg(feature = "zcash-sapling-prover")]
    Sapling(crate::sapling::builder::Error),
    /// The Orchard bundle could not be built or signed.
    #[cfg(feature = "zcash-orchard-prover")]
    Orchard(crate::orchard::builder::BuildError),
    /// An amount is above the money supply.
    ValueOutOfRange,
    /// The outputs are worth more than the inputs.
    InsufficientFunds,
    /// The fee the transaction pays is not the one the caller stated.
    FeeMismatch {
        /// The fee given to [`Builder::build`].
        stated: u64,
        /// The fee the inputs and outputs imply.
        actual: u64,
    },
    /// The transaction has neither inputs nor outputs.
    Empty,
    /// A shielded part needs the anchor of its pool, which was not set.
    MissingAnchor,
    /// An anchor or a circuit version can only be set before the first
    /// part of its pool is added.
    AlreadyStarted,
    /// The Orchard circuit version of the consensus branch id is not
    /// known: it must be set explicitly.
    UnknownCircuitVersion,
    /// The Orchard bundle needs a proving key, which was not supplied.
    MissingProvingKey,
    /// The transaction version is not valid under the consensus branch:
    /// version 6 before NU6.3.
    VersionNotActive,
    /// The transaction has Ironwood parts, which only a version 6
    /// transaction can carry.
    IronwoodNeedsV6,
    /// The Orchard bundle takes more value in than it spends, which
    /// consensus forbids from NU6.3 (ZIP 258): what is to be shielded
    /// goes to the Ironwood pool. Also an Orchard output in a coinbase
    /// transaction from NU6.3, which can have no Orchard action.
    OrchardPoolClosed,
    /// A coinbase transaction spends nothing and is built with
    /// [`Builder::build_coinbase`]; any other transaction is not.
    Coinbase,
    /// The transaction has an output to a TEX address (ZIP 320), which
    /// must be paid from transparent funds only, and shielded spends.
    TransparentSourceOnly,
    /// The transparent input of this index is signed elsewhere, and its
    /// signatures were not given.
    MissingTransparentSignature(usize),
    /// The unified address has no transparent receiver.
    NoTransparentReceiver,
}

impl core::fmt::Display for Error {
    fn fmt(&self, f: &mut core::fmt::Formatter<'_>) -> core::fmt::Result {
        match self {
            Error::Tx(e) => write!(f, "{e}"),
            #[cfg(feature = "zcash-sapling-prover")]
            Error::Sapling(e) => write!(f, "sapling: {e}"),
            #[cfg(feature = "zcash-orchard-prover")]
            Error::Orchard(e) => write!(f, "orchard: {e}"),
            Error::ValueOutOfRange => f.write_str("amount above the money supply"),
            Error::InsufficientFunds => f.write_str("the outputs exceed the inputs"),
            Error::FeeMismatch { stated, actual } => {
                write!(f, "the fee is {actual} zatoshis, not the stated {stated}")
            }
            Error::Empty => f.write_str("empty transaction"),
            Error::MissingAnchor => f.write_str("the anchor of the pool is not set"),
            Error::AlreadyStarted => f.write_str("the pool already has parts"),
            Error::UnknownCircuitVersion => {
                f.write_str("unknown Orchard circuit version for the consensus branch")
            }
            Error::MissingProvingKey => f.write_str("missing Orchard proving key"),
            Error::VersionNotActive => {
                f.write_str("transaction version not valid under the consensus branch")
            }
            Error::IronwoodNeedsV6 => f.write_str("Ironwood parts need a version 6 transaction"),
            Error::OrchardPoolClosed => {
                f.write_str("no value can enter the Orchard pool from NU6.3")
            }
            Error::Coinbase => f.write_str("not possible in, or only in, a coinbase transaction"),
            Error::TransparentSourceOnly => {
                f.write_str("an output to a TEX address needs transparent funds only")
            }
            Error::MissingTransparentSignature(index) => {
                write!(f, "transparent input {index} is not signed")
            }
            Error::NoTransparentReceiver => f.write_str("no transparent receiver"),
        }
    }
}

impl core::error::Error for Error {}

impl From<crate::Error> for Error {
    fn from(e: crate::Error) -> Self {
        Error::Tx(e)
    }
}

