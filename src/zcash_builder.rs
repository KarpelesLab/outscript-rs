//! Building whole Zcash v5 transactions (features `zcash` and `alloc`):
//! transparent inputs and outputs, and, with the prover features, Sapling
//! spends and outputs (`zcash-sapling-prover`) and Orchard spends and
//! outputs (`zcash-orchard-prover`), in one [`Builder`].
//!
//! The builder collects the parts, checks that the values balance, has the
//! shielded bundles built and proven, computes the ZIP-244 transaction id
//! and signature hash, signs everything (the transparent inputs, the
//! Sapling spends and the Orchard actions, and both bundles' binding
//! signatures) and serializes the transaction:
//!
//! ```
//! use outscript::crypto::secp256k1::SecpPrivateKey;
//! use outscript::zcash_builder::{Builder, Provers};
//! use outscript::zcashtx::{ZcashTxOut, branch};
//! use outscript::{generate_script, PubKey};
//!
//! let key = SecpPrivateKey::from_bytes(&[7u8; 32]).unwrap();
//! let mine = generate_script(&PubKey::Secp256k1(key.public_key()), "p2pkh").unwrap();
//! # let random = [0x55u8; 64]; // from a secure generator, in real use
//!
//! let mut builder = Builder::new(branch::NU6_2, 3_400_000, 0);
//! // the coin to spend: its outpoint, and the output it is
//! let coin = ZcashTxOut { amount: 100_000, script: &mine };
//! builder.add_transparent_input(&key, [0x11; 32], 1, 0xffff_ffff, coin).unwrap();
//! builder.add_transparent_output(90_000, &mine).unwrap();
//!
//! // what is not sent is the fee, which is stated to be checked
//! assert_eq!(builder.fee(), Ok(10_000));
//! assert_eq!(builder.conventional_fee(), 10_000);
//! let tx = builder.build(&Provers::new(), 10_000, &random).unwrap();
//! assert!(tx.raw.len() > 150);
//! ```
//!
//! # What the caller supplies
//!
//! - **The chain context**: the consensus branch id of the network upgrade
//!   in force when the transaction will be mined
//!   ([`branch`](crate::zcashtx::branch)), an expiry height and a lock
//!   time. A transaction made for one upgrade is invalid under another.
//! - **Transparent inputs**: the outpoint, the amount and scriptPubKey of
//!   the output it spends (a P2PKH output), and its private key.
//! - **Sapling spends** (`add_sapling_spend`): the expanded spending key,
//!   the note (as found when scanning), its Merkle path in the Sapling
//!   note commitment tree and the root of that tree, the *anchor*, which
//!   every spend of the transaction shares (`set_sapling_anchor`) and
//!   which must be the tree's root at the end of some block of the chain.
//! - **Orchard spends** (`add_orchard_spend`): the spending key, the note,
//!   its Merkle path, and likewise the anchor of the Orchard tree
//!   (`set_orchard_anchor`), which is needed even without spends.
//! - **Proving parameters** ([`Provers`]): the Sapling Spend and Output
//!   parameters (`sapling-spend.params` and `sapling-output.params`, as
//!   read by `sapling::prover`) when there are Sapling spends or outputs,
//!   and the Orchard proving key of the circuit version of the consensus
//!   branch (generated by `orchard::circuit::ProvingKey::build`, once)
//!   when there is anything Orchard.
//! - **Randomness**: the crate has no random number generator. Each
//!   Sapling spend and output takes its own random bytes, as in
//!   `sapling::builder`, and [`Builder::build`] takes 64 more, from which
//!   the randomness of the Orchard bundle and of every shielded signature
//!   is derived. All must come fresh from a cryptographically secure
//!   generator: reusing or predicting them reveals values, links spends
//!   or leaks keys.
//! - **The fee**. The builder adds no change output: the fee is the value
//!   that goes in and does not come out, [`Builder::fee`]. To avoid paying
//!   an unintended one, [`Builder::build`] is told the fee and fails if it
//!   is not exactly that. [`Builder::conventional_fee`] gives the fee
//!   ZIP-317 asks of the transaction as it stands.
//!
//! # Value pools
//!
//! Each pool has a balance, positive when value leaves it: the sum of the
//! transparent inputs minus the transparent outputs, the Sapling value
//! balance (spends minus outputs, the `valueBalanceSapling` field) and the
//! Orchard one (`valueBalanceOrchard`). Their sum is the fee, which cannot
//! be negative. Value moves between pools simply by spending in one and
//! outputting in another.
//!
//! # Orchard circuit versions
//!
//! The Orchard proof is made for the circuit version of the consensus
//! branch (`orchard_circuit_version`). From NU6.3 a note can only be
//! created at the address of a note spent in the same bundle, which the
//! Orchard builder enforces (see `orchard::builder`).

