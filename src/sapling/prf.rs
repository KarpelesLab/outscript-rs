//! The personalized BLAKE2 hashes and pseudo-random functions Sapling is
//! built from (protocol specification §5.4.1 and §5.4.2).

use purecrypto::hash::{Blake2bMac, Blake2sMac};

/// BLAKE2s-256 of the concatenation of `parts`, personalized with `person`.
pub fn blake2s_256(person: &[u8; 8], parts: &[&[u8]]) -> [u8; 32] {
    let mut h = Blake2sMac::try_new_with_salt_personal(&[], 32, &[], person)
        .expect("valid BLAKE2s parameters");
    for part in parts {
        h.update(part);
    }
    let mut out = [0u8; 32];
    h.finalize_into(&mut out);
    out
}

/// BLAKE2b of the concatenation of `parts`, personalized with `person`, with
/// an output of `N` bytes (1 to 64). The hash state is wiped afterwards.
pub fn blake2b<const N: usize>(person: &[u8; 16], parts: &[&[u8]]) -> [u8; N] {
    let mut h = Blake2bMac::try_new_with_salt_personal(&[], N, &[], person)
        .expect("valid BLAKE2b parameters");
    for part in parts {
        h.update(part);
    }
    let mut out = [0u8; N];
    h.finalize_into(&mut out);
    out
}

/// `PRF^expand(sk, t)`: BLAKE2b-512 personalized `Zcash_ExpandSeed` of
/// `sk ‖ t`, where `t` is given in pieces. The output is key material: wipe
/// it once used.
pub fn prf_expand(sk: &[u8], t: &[&[u8]]) -> [u8; 64] {
    let mut h = Blake2bMac::try_new_with_salt_personal(&[], 64, &[], b"Zcash_ExpandSeed")
        .expect("valid BLAKE2b parameters");
    h.update(sk);
    for part in t {
        h.update(part);
    }
    let mut out = [0u8; 64];
    h.finalize_into(&mut out);
    out
}

/// `PRF^nfSapling(nk, rho)`: BLAKE2s-256 personalized `Zcash_nf` of the two
/// compressed points.
pub fn prf_nf(nk: &[u8; 32], rho: &[u8; 32]) -> [u8; 32] {
    blake2s_256(b"Zcash_nf", &[nk, rho])
}

/// `CRH^ivk(ak, nk)`: BLAKE2s-256 personalized `Zcashivk`, truncated to 251
/// bits, as the little-endian encoding of the incoming viewing key.
pub fn crh_ivk(ak: &[u8; 32], nk: &[u8; 32]) -> [u8; 32] {
    let mut ivk = blake2s_256(b"Zcashivk", &[ak, nk]);
    ivk[31] &= 0x07;
    ivk
}

/// `KDF^Sapling(shared_secret, ephemeral_key)`: the symmetric key of a note
/// ciphertext.
pub fn kdf_sapling(shared_secret: &[u8; 32], ephemeral_key: &[u8; 32]) -> [u8; 32] {
    blake2b(b"Zcash_SaplingKDF", &[shared_secret, ephemeral_key])
}

/// `PRF^ock(ovk, cv, cmu, ephemeral_key)`: the key of an output's outgoing
/// ciphertext.
pub fn prf_ock(
    ovk: &[u8; 32],
    cv: &[u8; 32],
    cmu: &[u8; 32],
    ephemeral_key: &[u8; 32],
) -> [u8; 32] {
    blake2b(b"Zcash_Derive_ock", &[ovk, cv, cmu, ephemeral_key])
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Known answers from Python's `hashlib`, generated by
    /// `testdata/blake2.py`.
    #[test]
    fn personalized_hashes_match_hashlib() {
        let expected: Vec<&str> = include_str!("testdata/blake2.txt").lines().collect();
        assert_eq!(
            hex::encode(blake2s_256(b"Zcash_nf", &[b"a", b"bc"])),
            expected[0]
        );
        assert_eq!(hex::encode(prf_expand(b"a", &[b"b", b"c"])), expected[1]);
        assert_eq!(
            hex::encode(blake2b::<32>(b"Zcash_ExpandSeed", &[b"abc"])),
            expected[2]
        );
    }
}
